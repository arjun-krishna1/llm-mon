"""Writes docs/ART_CATALOG_EXTERIOR.md from the built sheet."""


def _grid(g):
    return '\n'.join('    ' + ' '.join('%4d' % v for v in row) for row in g)


def write(path, sh):
    L = []
    w = L.append
    w('# Exterior tileset catalog (ART-EXT)')
    w('')
    w('Generated by `python3 tools/art/tiles_exterior/build.py` (one command rebuilds the PNG, TSJ, '
      'catalog, this file and the previews). Files:')
    w('')
    w('- `public/assets/game/tilesets/exterior.png` - 16x16 tiles, 16 columns, no margin/spacing.')
    w('- `public/assets/game/tilesets/exterior.tsj` - Tiled tileset: per-tile properties '
      '(`solid`, `grass`, `ledge`, `water`, `door`) and `animation` arrays (water 4x280 ms, flowers 2x600 ms, tall grass 2x650 ms, fountain 3x220 ms, signal-tower beacon 700/500 ms).')
    w('- `public/assets/game/tilesets/exterior.catalog.json` - the names below -> tile ids (0-based, '
      'i.e. Tiled gid minus firstgid). `-1` = leave the cell empty.')
    w('- Previews: `tools/art/tiles_exterior/preview/` (`tileset_4x.png`, `scene_3x.png`, '
      '`scene_frame_4x.png`). `preview.py` contains a small reference implementation of every '
      'placement rule below (`Map.area`, `Map.forest`, `Map.fence`, `Map.stamp`) - copy it.')
    w('')
    w('Art sources: ground, path/sand/water edge sets, ledges, tall grass, flowers and fences are '
      'hand-placed pixels in code (`ground.py`, `props.py`). Buildings, the tree, bush, rocks, signs, '
      'mailbox, lamp and bench are generated source images (`gen_sources.py`, cached in '
      '`tools/art/gen/raw/ext_*.png`), pixelized and snapped to `tools/art/palette.py`, then '
      'hand-corrected in `buildings.py` / `nature.py`.')
    w('')
    w('## Layers')
    w('')
    w('| map layer | what goes there |')
    w('| --- | --- |')
    w('| `ground` | grass variants, flowers, tall grass, path / sand / water autotiles, ledges, steps (all opaque) |')
    w('| `detail` | stamp `base` layers (buildings, trees, props), forest pieces, fences, bush, rock, sign, mailbox (transparent backgrounds) |')
    w('| `detail2` | anything that must sit on top of a detail tile (rare) |')
    w('| `over` | stamp `over` layers: roof tops, tree crown tops, lamp heads, town-sign board. Drawn above characters so the player walks behind them. Never solid. |')
    w('')
    w('Stamps: copy `layers.base` into `detail` and `layers.over` into `over` at the same origin '
      '(top-left). Skip `-1` cells. Solid / door properties are already on the tiles.')
    w('')
    w('## Single tiles (`tiles`)')
    w('')
    w('| name | id | notes |')
    w('| --- | --- | --- |')
    notes = {
        'grass_a': 'default grass; mix a/b/c/d randomly (about 40/15/15/30%) for natural ground',
        'grass_d': 'calmest variant, use most under props/flowers',
        'tall_grass': '`grass: true` (encounters + rustle), 2-frame sway. Interior of a patch',
        'tall_grass_top': '`grass: true`, 2-frame sway. Use on the TOP row of a patch (blade tips over grass)',
        'flower_red': 'animated (2 frames). Walkable. Also flower_yellow/white/pink',
        'steps': 'walkable earth steps cut through a down-ledge: ledge_s_end_e, steps, ledge_s_end_w',
        'ledge_s': '`ledge: down` - hop south. Repeat horizontally',
        'ledge_s_end_w': 'west end cap of a down-ledge', 'ledge_s_end_e': 'east end cap',
        'ledge_w': '`ledge: left` - plateau to the east, hop west. Repeat vertically',
        'ledge_w_end_n': 'north end cap of a left-ledge',
        'ledge_e': '`ledge: right` - plateau to the west, hop east',
        'ledge_e_end_n': 'north end cap of a right-ledge',
        'ledge_corner_sw': '`ledge: down`. joins ledge_w (north of it) to ledge_s (east of it): SW corner of a plateau',
        'ledge_corner_se': '`ledge: down`. joins ledge_e (north) to ledge_s (west): SE corner of a plateau',
        'bush': 'solid, detail layer', 'rock': 'solid, detail layer',
        'sign_wood': 'solid, detail layer; put a `sign` object on it',
        'mailbox': 'solid, detail layer',
        'bush_flower': 'flowering shrub, solid, detail layer',
        'stump': 'tree stump, solid, detail layer',
        'lilypad': 'transparent overlay: put on the detail layer over a water tile (water below stays animated + solid)',
        'reeds': 'cattail reeds, transparent overlay, solid: detail layer on a water edge cell or the grass beside a pond',
        'planter': 'stone flower box, solid, detail layer',
        'crate': 'wooden crate, solid, detail layer',
    }
    for n, i in sh.tiles.items():
        w('| `%s` | %d | %s |' % (n, i, notes.get(n, '')))
    w('')
    w('## Stamps (`stamps`)')
    w('')
    w('| name | w x h | over rows | doors (stamp-relative x,y) | notes |')
    w('| --- | --- | --- | --- | --- |')
    snotes = {
        'tree': 'single tree; row 0 crown top is `over`, rows 1-2 solid. For rows of trees use the `forest` autotile',
        'rock_big': 'solid boulder',
        'lamp': 'head in `over`, post solid',
        'sign_town': 'town welcome board; top row `over`, bottom row solid (put the `sign` object on the bottom row)',
        'bench': 'solid',
        'house_orange': 'player house (orange roof, chimney)',
        'house_blue': 'neighbour house (blue roof, flower boxes)',
        'lab': "professor's lab: wide, slate roof with skylights + satellite dish, glass doors",
        'model_center': 'Model Center (heal): teal roof, chip/plus emblem, double glass doors (both door tiles)',
        'token_mart': 'Token Mart: violet roof, gold coin "T" sign, awning',
        'gym': 'closed gym-like arena: boarded-up doors, brain-circuit emblem',
        'shed': 'small tool shed',
        'tree_b': 'conifer variant of `tree` (same 2x3 layout). Standalone only: not part of the forest autotile',
        'fountain': 'plaza fountain, animated water (3 frames). Spout row is `over` (walk behind), lower 2 rows solid',
        'signal_tower': 'relay mast landmark with a blinking beacon (2 frames). Top row `over`, rest solid',
    }
    for n, st in sh.stamps.items():
        ov = 0
        if 'over' in st['layers']:
            ov = sum(1 for row in st['layers']['over'] if any(v >= 0 for v in row))
        doors = ', '.join('(%d,%d)' % (d['x'], d['y']) for d in st.get('door', [])) or '-'
        w('| `%s` | %dx%d | %d | %s | %s |' % (n, st['w'], st['h'], ov, doors, snotes.get(n, '')))
    w('')
    w('Buildings: every `base` cell is `solid` except the door cell(s) on the bottom row, which carry '
      '`door: true` (walkable; put the `warp` object there). The path should run along the row directly '
      'below the stamp (the door step is drawn inside the stamp). Roof rows above the footprint are '
      '`over` and walkable, so the player can pass behind a building. Leave one free row between a '
      'building\'s over rows and anything solid above it if you want that walk-behind lane.')
    w('')
    w('## Autotiles (`autotiles`)')
    w('')
    w('### path, sand, water - 47-piece blob sets')
    w('')
    w('Paint a set of cells as the material. Each material cell keeps a ~3 px grass margin where it '
      'borders grass, so the edge (and the rounded corners) are drawn INSIDE the material cells; plain '
      'grass cells around it stay plain `grass_*`. All on the `ground` layer. Water tiles are '
      '`water: true, solid: true` and animated; path and sand are walkable.')
    w('')
    w('Named pieces (name = side where the GRASS is): `c`, `n`, `s`, `e`, `w`, outer corners '
      '`nw`, `ne`, `sw`, `se`, inner (concave) corners `inner_nw`, `inner_ne`, `inner_sw`, `inner_se` '
      '(material on all four sides, grass only in that diagonal). Example: the top-left cell of a '
      'rectangle of path is `nw`; the cell of an L-shaped path where grass pokes in at its NE '
      'diagonal is `inner_ne`.')
    w('')
    w('`blob` covers every case including 1-tile-wide strips, ends and T-junctions. Key = 8 chars, '
      'one per neighbour in the order `n ne e se s sw w nw`, `1` = same material. Diagonals count '
      'only when both adjacent orthogonals are material (otherwise write `0`). Treat cells beyond '
      'the map edge as material. Pseudocode:')
    w('')
    w('```')
    w('nb = {d: is_material(x+dx, y+dy) for d in n,ne,e,se,s,sw,w,nw}')
    w('for d,(a,b) in {ne:(n,e), se:(s,e), sw:(s,w), nw:(n,w)}: if not (nb[a] and nb[b]): nb[d]=0')
    w("key = ''.join('1' if nb[d] else '0' for d in [n,ne,e,se,s,sw,w,nw])")
    w("tile = catalog.autotiles.path.blob[key]")
    w('```')
    w('')
    w('Water also has `c_variants`: three interchangeable all-water centre tiles with different ripple '
      'layouts. Whenever the blob key is `11111111`, pick one by a position hash so big ponds do not '
      'tile visibly. Dress ponds with `lilypad` (detail layer over water) and `reeds` (solid).')
    w('')
    w('Path, sand and water each have their own grass margin, so they do not butt against each other; '
      'separate two materials by at least one grass cell (a pond inside a beach is not supported).')
    w('')
    w('### forest - walls of trees')
    w('')
    w('Trees sit on a lattice of anchors `(ax, ay)`; a tree covers columns `ax..ax+1` and rows '
      '`ay..ay+2` (top, mid, bottom). Rows of trees stack every 2 rows so each crown overlaps the '
      'trunks behind it; columns sit every 2 tiles. For a rectangle: anchors at x = x0, x0+2, ... and '
      'y = y0, y0+2, ...; the block is `2*cols` wide and `2*rows+1` tall. Anchors may sit outside the '
      'map (e.g. ay = -1) to crop the wall at the edge. Per anchor, for each of its 3 rows:')
    w('')
    w('- row kind: `top`; becomes `join` if there is a tree at `(ax, ay-2)`; `mid`; `bottom` '
      '(skip the bottom row if there is a tree at `(ax, ay+2)` - its `join` row covers it).')
    w('- left cell: `l_in` if a tree at `(ax-2, ay)` else `l_out`; right cell: `r_in` if a tree at '
      '`(ax+2, ay)` else `r_out`.')
    w('- tile = `forest[<row kind>_<col kind>]`, on the `detail` layer. All forest tiles are solid. '
      'Gaps between crowns inside the wall are filled with deep foliage; the outer silhouette stays '
      'open and shows the ground layer.')
    w('')
    w('See `Map.forest` in `preview.py`. Single trees in the open use the `tree` stamp instead.')
    w('')
    w('### fence_wood, fence_white')
    w('')
    w('Paint fence cells (detail layer, all solid). `byConnection[conn]` where `conn` lists the '
      'neighbouring fence cells in the order `n e s w` (e.g. `"ew"` horizontal run, `"ns"` vertical, '
      '`"es"` top-left corner, `""` lone post). Friendly aliases: `h`, `v`, `end_w`, `end_e`, `end_n`, '
      '`end_s`, `corner_nw`, `corner_ne`, `corner_sw`, `corner_se`, `t_n`, `t_s`, `t_e`, `t_w`, `cross`, `post`.')
    w('')
    w('## Ledges in practice')
    w('')
    w('A down-ledge line on Route 101: `ledge_s_end_w, ledge_s x N, ledge_s_end_e`. To leave a gap you '
      'can walk up, put `steps` between an `ledge_s_end_e` and an `ledge_s_end_w`. For a raised '
      'plateau: left side `ledge_w_end_n` then `ledge_w` x N, bottom-left `ledge_corner_sw`, bottom '
      '`ledge_s` x N, bottom-right `ledge_corner_se`, right side `ledge_e` x N topped by `ledge_e_end_n`. '
      'Ledges are ground tiles (grass baked in); the plateau top and the lower ground are ordinary grass.')
    w('')
    w('## Known limits')
    w('')
    w('- Path/sand/water must be separated by a grass cell (each has its own grass margin).')
    w('- Ledge inner (concave) corners are not provided; build plateaus as convex shapes.')
    w('- Forest pieces assume walls built from whole trees on the 2x2 lattice (rectangles and '
      'L/U shapes made of rectangles work).')
    w('- Building art is pixelized from generated images, so outlines are slightly less regular than '
      'the hand-placed ground tiles.')
    with open(path, 'w') as f:
        f.write('\n'.join(L) + '\n')
